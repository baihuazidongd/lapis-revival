#!/usr/bin/env python3
"""Write the landing-safe TabIndex map into the client's master database.

make_state.py computes which ShopData rows actually reach the client (a shop only appears if its
ShopGoods list resolves to real GoodsData rows) and picks one row per type to hold that type's tab-bar
slot; every other row is given TabIndex 4. Because ShopManager.SetData writes listAllType[Type] from
the last row it sees of a type and listAllIndex[TabIndex] from the last row seen at that index, that
shape makes listAllType[t] = 4 for every t while listAllIndex[4] stays Type 2 -- so whichever tab an
entry asks for, PageShop lands on 道具, whose UpdateTag branch is the one that re-activates
SafeArea/Main/ScrollArea before InitScrollView looks it up by path.

The two files have to agree exactly, so the map is generated by make_state.py into
stubapp/assets/shop_tabindex.json and applied here; the Seed pin is rewritten in the same step because
Seed refuses to install a database whose hash it has not been told about.
"""
import hashlib
import json
import sqlite3
import sys

DB = 'C:/lapisbuild/game_decoded/assets/res/MasterData/master_data.db'
SEED = 'C:/lapisbuild/stubapp/src/com/klab/lapis/stub/Seed.java'
MAP = 'C:/lapisbuild/stubapp/assets/shop_tabindex.json'

sha1 = lambda p: hashlib.sha1(open(p, 'rb').read()).hexdigest().upper()
old = sha1(DB)
plan = {int(k): v for k, v in json.load(open(MAP, encoding='utf-8')).items()}

db = sqlite3.connect(DB)
rows = dict(db.execute('select ID, TabIndex from ShopData'))
missing = [i for i in plan if i not in rows]
if missing:
    sys.exit('plan references %d shop rows that are not in ShopData: %r' % (len(missing), missing[:5]))
for sid, slot in sorted(plan.items()):
    db.execute('update ShopData set TabIndex = ? where ID = ?', (slot, sid))
db.commit()
groups = db.execute('select Type, TabIndex, count(*) from ShopData group by Type, TabIndex '
                    'order by Type, TabIndex').fetchall()
db.close()
new = sha1(DB)
print('applied %d TabIndex assignments' % len(plan))
print('Type/TabIndex row counts:', groups)
print('db sha1 %s -> %s' % (old, new))

text = open(SEED, encoding='utf-8', newline='').read()
if old not in text:
    sys.exit('Seed.java pin %s not found -- refusing to guess where it goes' % old)
open(SEED, 'w', encoding='utf-8', newline='').write(text.replace(old, new))
print('Seed.java pin rewritten: %s -> %s' % (old, new))
