    String mirrorEventState(DynamicMessage request) throws Exception {
        org.json.JSONObject cfg = mirrorCfg();
        if (cfg == null) return "{}";
        int mirror = (int) getFieldLong(request, "mirrorId");
        state().edit().putInt("mir_last", mirror).apply();
        StringBuilder sb = new StringBuilder("{\"result\":{\"code\":0},\"progress\":")
                .append(state().getInt("mir_" + mirror + "_progress", 0));
        sb.append(",\"eventValue\":").append(state().getInt("mir_" + mirror + "_event_value", 0));
        // The doors on the grid are ClubMirrorEvent ids (RoundEvent's {1,2,3} for mirror 1 are events
        // 1/2/3, and the middle door's "+2" badge is that event's Contribution). So P182 answers with
        // the payload of the event that was tapped - TypeValue - not with the round layout.
        int eventId = (int) getFieldLong(request, "eventId");
        org.json.JSONObject ev = mirrorEvent(cfg, eventId);
        StringBuilder params = new StringBuilder("[");
        if (ev != null) {
            org.json.JSONArray pp = ev.optJSONArray("params");
            for (int i = 0; pp != null && i < pp.length(); i++) {
                if (i > 0) params.append(',');
                params.append(pp.optInt(i));
            }
        }
        params.append(']');
        sb.append(",\"eventParams\":").append(params);
        return sb.append("}").toString();
    }

    /**
     * P183 is the "do the event" call: it spends one of the daily actions, adds the event's AddPoint to
     * that mirror's progress and its Contribution to the weekly 应援值, both straight out of
     * ClubMirrorEvent. `assets` is not a field on this response, so nothing is paid here.
     */
    String mirrorEventFinish(DynamicMessage request) throws Exception {
        org.json.JSONObject cfg = mirrorCfg();
        if (cfg == null) return "{\"result\":{\"code\":0}}";
        android.content.SharedPreferences st = state();
        int mirror = (int) getFieldLong(request, "mirrorId");
        int eventId = (int) getFieldLong(request, "eventId");
        org.json.JSONObject e = mirrorEvent(cfg, eventId);
        String p = "mir_" + mirror + "_";
        int round = st.getInt(p + "round", 0);
        // addPoint is per-round ({1,1,2,3,4} = what rounds 1..5 each award), so index it rather than
        // summing or reading it as a scalar - optInt on an array silently yields 0, which would have
        // looked like "progress never moves" with no error anywhere.
        int add = 0;
        if (e != null) {
            org.json.JSONArray ap = e.optJSONArray("addPoint");
            if (ap != null && ap.length() > 0) add = ap.optInt(Math.min(round, ap.length() - 1));
        }
        int value = st.getInt(p + "event_value", 0) + 1;
        android.content.SharedPreferences.Editor ed = st.edit();
        ed.putInt(p + "event", eventId).putInt(p + "event_value", value)
          .putBoolean(p + "event_finish", true)
          .putInt(p + "battles", st.getInt(p + "battles", 0) + 1)
          .putInt(p + "round", Math.min(cfg.optInt("maxRound", 10) - 1, round + 1))
          .putInt(p + "progress", st.getInt(p + "progress", 0) + add)
          .putInt("mir_contrib", st.getInt("mir_contrib", 0) + (e == null ? 0 : e.optInt("contribution", 0)))
          .putInt("mir_bout", Math.min(cfg.optInt("dailyRound", 10), mirrorBoutUsed(cfg, st) + 1))
          .putLong("mir_bout_day", System.currentTimeMillis() / 86400000L);
        ed.apply();
        return "{\"result\":{\"code\":0},\"eventValue\":" + value + "}";
    }

    /**
     * P184 is the claim. mirrorId 1..5 pays that mirror's ClubMirror.Award once its FinishPoint is
     * reached; mirrorId 0 is the weekly 应援值 bar, whose tiers come from
     * Config ClubMirrorContributionAward -> DropGroup (we grant NumMin, the guaranteed floor, rather
     * than inventing a roll). P184_Response has no `setter` field, so the client applies `assets`
     * itself; the shape is one PBAward per [item, num] pair, same as PBMailAward.
     */
    String mirrorClaim(DynamicMessage request) throws Exception {
        org.json.JSONObject cfg = mirrorCfg();
        if (cfg == null) return "{\"result\":{\"code\":0}}";
        android.content.SharedPreferences st = state();
        int mirror = (int) getFieldLong(request, "mirrorId");
        StringBuilder assets = new StringBuilder();
        boolean more = false;
        if (mirror <= 0) {
            org.json.JSONArray tiers = cfg.optJSONArray("contributionAward");
            int contrib = st.getInt("mir_contrib", 0);
            String claimed = st.getString("mir_contrib_award", "");
            StringBuilder now = new StringBuilder(claimed);
            for (int i = 0; tiers != null && i < tiers.length(); i++) {
                org.json.JSONObject t = tiers.getJSONObject(i);
                int need = t.getInt("need");
                if (contrib < need || ("," + now + ",").contains("," + need + ",")) continue;
                org.json.JSONArray items = t.optJSONArray("items");
                for (int j = 0; items != null && j < items.length(); j++) {
                    org.json.JSONArray row = items.getJSONArray(j);
                    if (more) assets.append(',');
                    more = true;
                    assets.append("{\"awards\":[").append(row.getInt(0)).append(',').append(row.getInt(1)).append("]}");
                }
                if (now.length() > 0) now.append(',');
                now.append(need);
            }
            st.edit().putString("mir_contrib_award", now.toString()).apply();
        } else {
            String p = "mir_" + mirror + "_";
            org.json.JSONArray ms = cfg.optJSONArray("mirrors");
            org.json.JSONObject m = null;
            for (int i = 0; ms != null && i < ms.length(); i++)
                if (ms.getJSONObject(i).getInt("id") == mirror) m = ms.getJSONObject(i);
            if (m != null && !st.getBoolean(p + "award", false)
                    && st.getInt(p + "progress", 0) >= m.optInt("finishPoint", 65)) {
                org.json.JSONArray aw = m.optJSONArray("award");
                for (int i = 0; aw != null && i < aw.length(); i++) {
                    org.json.JSONArray row = aw.getJSONArray(i);
                    if (more) assets.append(',');
                    more = true;
                    assets.append("{\"awards\":[").append(row.getInt(0)).append(',').append(row.getInt(1)).append("]}");
                }
                st.edit().putBoolean(p + "award", true).apply();
            }
        }
        return "{\"result\":{\"code\":0},\"assets\":[" + assets + "]}";
    }

    /** P186 records which card teams the player assigned to the mirror and the boss. */
