    /**
     * build() walks the whole tree checking proto2 required fields, and one unset field buried in a
     * nested message throws here so the client sees the same connection-timeout dialog as if the
     * response had never arrived, so descend into every message the JSON merge placed before that
     * check. The request round-trip only applies at the top level; nested fields take zero values.
     */
    void fillRequiredTree(DynamicMessage.Builder rb, int protocol, int depth) {
        if (depth > 12) return;
        for (Descriptors.FieldDescriptor f : rb.getDescriptorForType().getFields()) {
            if (f.getJavaType() != Descriptors.FieldDescriptor.JavaType.MESSAGE) continue;
            if (f.isRepeated()) {
                int n = rb.getRepeatedFieldCount(f);
                if (n == 0) continue;
                java.util.List<Object> rebuilt = new java.util.ArrayList<Object>(n);
                for (int i = 0; i < n; i++) {
                    DynamicMessage.Builder sub = ((DynamicMessage) rb.getRepeatedField(f, i)).toBuilder();
                    fillRequired(sub, null, protocol);
                    fillRequiredTree(sub, protocol, depth + 1);
                    rebuilt.add(sub.buildPartial());
                }
                rb.clearField(f);
                for (Object m : rebuilt) rb.addRepeatedField(f, m);
            } else if (rb.hasField(f)) {
                DynamicMessage.Builder sub = ((DynamicMessage) rb.getField(f)).toBuilder();
                fillRequired(sub, null, protocol);
                fillRequiredTree(sub, protocol, depth + 1);
                rb.setField(f, sub.buildPartial());
            }
        }
    }

    /**
     * The client's protobuf-net rejects a response missing any proto2 required field, and it reports
     * that as a connection timeout dialog rather than a schema problem, so every required field the
     * per-protocol builders left unset gets one here: the request's same-named value where there is one
     * (termsVersion round-trips exactly this way), otherwise the type's zero value.
     */
    void fillRequired(DynamicMessage.Builder rb, DynamicMessage request, int protocol) {
        StringBuilder filled = null;
        for (Descriptors.FieldDescriptor f : rb.getDescriptorForType().getFields()) {
            if (!f.isRequired() || rb.hasField(f)) continue;
            Object v = null;
            if (request != null && f.getJavaType() != Descriptors.FieldDescriptor.JavaType.MESSAGE
                    && f.getJavaType() != Descriptors.FieldDescriptor.JavaType.ENUM) {
                Descriptors.FieldDescriptor rf = request.getDescriptorForType().findFieldByName(f.getName());
                if (rf != null && rf.getType() == f.getType() && !rf.isRepeated() && request.hasField(rf))
                    v = request.getField(rf);
            }
            if (v == null) v = zeroValue(f);
            if (v == null) continue;
            rb.setField(f, v);
            if (filled == null) filled = new StringBuilder();
            else filled.append(',');
            filled.append(f.getName());
        }
        if (filled != null) L.log(null, "required P" + protocol + " filled " + filled);
    }

    Object zeroValue(Descriptors.FieldDescriptor f) {
        switch (f.getJavaType()) {
            case INT: return 0;
            case LONG: return 0L;
            case BOOLEAN: return false;
            case FLOAT: return 0f;
            case DOUBLE: return 0d;
            case STRING: return "";
            case BYTE_STRING: return ByteString.EMPTY;
            case ENUM: return f.getEnumType().getValues().get(0);
            default: return null;
        }
    }

    /**
     * The client reads a response body through a C# property (vMsg.BodyString), and a 0-byte body
     * reaches it as a null payload: that getter throws, NetManager.lua:517 unwinds before it can
     * clear the pending group, and the dispatcher then re-delivers the same message every frame
     * forever -- 1,905 LuaExceptions from one P1012 in a single shop tab sweep. Twenty-one
     * responses carry no `result` and no required field, so anything this stub does not fill by
     * hand still has to ship at least one schema-valid field.
     */
    byte[] guardedBody(int protocol) {
        Descriptors.Descriptor d = bizMsg("P" + protocol + "_Response");
        if (d == null) return new byte[0];
        DynamicMessage.Builder rb = DynamicMessage.newBuilder(d);
        for (int pass = 0; pass < 2 && rb.buildPartial().getSerializedSize() == 0; pass++) {
            for (Descriptors.FieldDescriptor f : d.getFields()) {
                if (f.isRepeated() != (pass == 1)) continue;
                Object v = zeroFieldValue(f, 0);
                if (v == null) continue;
                if (f.isRepeated()) rb.addRepeatedField(f, v); else rb.setField(f, v);
                break;
            }
        }
        byte[] out = rb.buildPartial().toByteArray();
        L.log(null, "empty body guarded P" + protocol + " -> " + (out.length == 0 ? "still empty" : hex(out)));
        return out;
    }

    /** Zero value for a field; message fields recurse through their own required fields, depth
     *  capped because a few of these types reference themselves. */
    Object zeroFieldValue(Descriptors.FieldDescriptor f, int depth) {
        if (f.getJavaType() != Descriptors.FieldDescriptor.JavaType.MESSAGE) return zeroValue(f);
        if (depth >= 4) return DynamicMessage.newBuilder(f.getMessageType()).buildPartial();
        DynamicMessage.Builder nb = DynamicMessage.newBuilder(f.getMessageType());
        for (Descriptors.FieldDescriptor rf : f.getMessageType().getFields()) {
            if (!rf.isRequired()) continue;
            Object rv = zeroFieldValue(rf, depth + 1);
            if (rv != null) nb.setField(rf, rv);
        }
        return nb.buildPartial();
    }

