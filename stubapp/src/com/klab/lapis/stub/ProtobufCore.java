    static byte[] bytesFromHex(String hex) {
        byte[] out = new byte[hex.length() / 2];
        for (int i = 0; i < out.length; i++)
            out[i] = (byte) Integer.parseInt(hex.substring(i * 2, i * 2 + 2), 16);
        return out;
    }

    // --- wire framing ---
    static byte[] frame(int protocol, int group, byte[] body) {
        byte[] out = new byte[body.length + 12];
        out[0] = (byte) ((body.length + 12) >>> 24); out[1] = (byte) ((body.length + 12) >>> 16);
        out[2] = (byte) ((body.length + 12) >>> 8); out[3] = (byte) (body.length + 12);
        putInt(out, 4, protocol); putInt(out, 8, group);
        System.arraycopy(body, 0, out, 12, body.length);
        return out;
    }

    static int[] unframe(byte[] data) {
        if (data.length < 12) throw new RuntimeException("Truncated protocol header");
        int length = getInt(data, 0);
        if (length != data.length) throw new RuntimeException("Frame length differs");
        return new int[]{getInt(data, 4), getInt(data, 8)};
    }

    static void putInt(byte[] a, int off, int v) {
        a[off] = (byte) (v >>> 24); a[off + 1] = (byte) (v >>> 16); a[off + 2] = (byte) (v >>> 8); a[off + 3] = (byte) v;
    }
    static int getInt(byte[] a, int off) {
        return ((a[off] & 0xFF) << 24) | ((a[off + 1] & 0xFF) << 16) | ((a[off + 2] & 0xFF) << 8) | (a[off + 3] & 0xFF);
    }

    static String hmacSha1Hex(byte[] key, byte[] data) {
        try {
            Mac mac = Mac.getInstance("HmacSHA1");
            mac.init(new SecretKeySpec(key, "HmacSHA1"));
            byte[] dg = mac.doFinal(data);
            StringBuilder sb = new StringBuilder();
            for (byte b : dg) sb.append(String.format("%02x", b));
            return sb.toString();
        } catch (Exception e) { throw new RuntimeException(e); }
    }

    byte[] signInput(int protocol, byte[] body, long playerId, String platform) {
        byte[] proto = {(byte) (protocol >>> 24), (byte) (protocol >>> 16), (byte) (protocol >>> 8), (byte) protocol};
        byte[] pid = new byte[8];
        long v = playerId;
        for (int i = 7; i >= 0; i--) { pid[i] = (byte) v; v >>>= 8; }
        byte[] plat = platform.getBytes(StandardCharsets.UTF_8);
        byte[] all = new byte[proto.length + body.length + pid.length + plat.length];
        int o = 0;
        System.arraycopy(proto, 0, all, o, proto.length); o += proto.length;
        System.arraycopy(body, 0, all, o, body.length); o += body.length;
        System.arraycopy(pid, 0, all, o, pid.length); o += pid.length;
        System.arraycopy(plat, 0, all, o, plat.length);
        return all;
    }

    String requestSignature(byte[] key, int protocol, byte[] body, long playerId, String platform) {
        return hmacSha1Hex(key, signInput(protocol, body, playerId, platform));
    }

    String responseSignature(byte[] key, int protocol, byte[] body) {
        byte[] proto = {(byte) (protocol >>> 24), (byte) (protocol >>> 16), (byte) (protocol >>> 8), (byte) protocol};
        byte[] all = new byte[proto.length + body.length];
        System.arraycopy(proto, 0, all, 0, proto.length);
        System.arraycopy(body, 0, all, proto.length, body.length);
        return hmacSha1Hex(key, all);
    }

    /** Length-safe XOR for diagnostics: the client's recovered key need not be 32 bytes. */

    static byte[] xor(byte[]... parts) {
        byte[] out = new byte[parts[0].length];
        for (int i = 0; i < out.length; i++) {
            byte x = parts[0][i];
            for (int j = 1; j < parts.length; j++) x ^= parts[j][i];
            out[i] = x;
        }
        return out;
    }

    /** The mask is base64 of the client's session pad; PublicEncrypt is neutralised by the
     *  bootstrap-identity patch, so what arrives is 32 bytes rather than a 128-byte RSA wrap. */
    static byte[] decodeMask(String s) {
        try {
            return java.util.Base64.getDecoder().decode(s);
        } catch (IllegalArgumentException e) {
            return s.getBytes(StandardCharsets.UTF_8);
        }
    }

    static byte[] requirePad(String mask) {
        byte[] pad = decodeMask(mask);
        if (pad.length != 32) {
            throw new RuntimeException("mask is " + pad.length + "B, expected a 32B pad: "
                    + "PublicEncrypt identity patch (libil2cpp 0x1ee25a0) is not in this build");
        }
        return pad;
    }

