    void mergeJson(DynamicMessage.Builder b, String json) throws Exception {
        mergeObject(b, new org.json.JSONObject(json));
    }

    void mergeObject(DynamicMessage.Builder b, org.json.JSONObject o) throws Exception {
        Descriptors.Descriptor d = b.getDescriptorForType();
        java.util.Iterator<String> it = o.keys();
        while (it.hasNext()) {
            String k = it.next();
            if (org.json.JSONObject.NULL.equals(o.get(k))) continue;
            Descriptors.FieldDescriptor f = d.findFieldByName(k);
            if (f == null) f = d.findFieldByName(k.replaceAll("([a-z0-9])([A-Z])", "$1_$2").toLowerCase());
            if (f == null) { L.log(null, "json has no home in the client schema: " + d.getFullName() + "." + k); continue; }
            Object v = o.get(k);
            if (f.isRepeated()) {
                org.json.JSONArray arr = v instanceof org.json.JSONArray ? (org.json.JSONArray) v
                        : new org.json.JSONArray().put(v);
                for (int i = 0; i < arr.length(); i++) b.addRepeatedField(f, jsonValue(f, arr.get(i)));
            } else {
                b.setField(f, jsonValue(f, v));
            }
        }
    }

    Object jsonValue(Descriptors.FieldDescriptor f, Object v) throws Exception {
        switch (f.getType()) {
            case MESSAGE: {
                DynamicMessage.Builder mb = DynamicMessage.newBuilder(f.getMessageType());
                mergeObject(mb, (org.json.JSONObject) v);
                return mb.buildPartial();
            }
            case ENUM: {
                Descriptors.EnumValueDescriptor e = v instanceof String
                        ? f.getEnumType().findValueByName((String) v)
                        : f.getEnumType().findValueByNumber(((Number) v).intValue());
                if (e == null) throw new RuntimeException("no enum value " + v + " in " + f.getEnumType().getFullName());
                return e;
            }
            case INT32: case SINT32: case SFIXED32: case UINT32: case FIXED32:
                return num(v).intValue();
            case INT64: case SINT64: case SFIXED64: case UINT64: case FIXED64:
                return num(v).longValue();
            case BOOL:   return v instanceof Boolean ? v : Boolean.valueOf(v.toString());
            case STRING: return v.toString();
            case BYTES:  return ByteString.copyFromUtf8(v.toString());
            case FLOAT:  return num(v).floatValue();
            case DOUBLE: return num(v).doubleValue();
            default:     throw new RuntimeException("unhandled field type " + f.getType() + " on " + f.getFullName());
        }
    }

    static Number num(Object v) {
        if (v instanceof Number) return (Number) v;
        String s = v.toString();
        return s.indexOf('.') >= 0 || s.indexOf('e') >= 0 || s.indexOf('E') >= 0
                ? (Number) Double.valueOf(s) : (Number) Long.valueOf(s);
    }
