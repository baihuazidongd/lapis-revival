    public byte[] call(byte[] raw) throws Exception {
        lock.lock();
        try {
            DynamicMessage req = parseMsg(commonMsg("CommonRequest"), raw);
            byte[] payload = getFieldBytes(req, "payload").toByteArray();
            String signature = getFieldString(req, "signature");
            long playerId = getFieldLong(req, "playerId");
            String platform = getFieldString(req, "platform");
            int[] pg = unframe(payload);
            int protocol = pg[0], group = pg[1];
            byte[] body = new byte[payload.length - 12];
            System.arraycopy(payload, 12, body, 0, body.length);
            byte[] key = verifyKey(protocol, body, playerId, platform, signature);
            L.log(null, "business_request P" + protocol + " group=" + group);
            byte[] bodyOut = buildBody(protocol, body);
            if (bodyOut.length == 0) bodyOut = guardedBody(protocol);
            String sig = responseSignature(key, protocol, bodyOut);
            if (!signature.isEmpty() && Character.isUpperCase(signature.charAt(0))) sig = sig.toUpperCase();
            String resVer = protocol == 9000 ? "" : manifestJson;
            DynamicMessage.Builder out = DynamicMessage.newBuilder(commonMsg("CommonResponse"));
            setOne(out, "payload", ByteString.copyFrom(frame(protocol, group, bodyOut)));
            setOne(out, "signature", sig);
            setOne(out, "status", 0);
            if (protocol != 9000) setOne(out, "resVer", resVer);
            setOne(out, "ts", System.currentTimeMillis());
            return toBytes(out.build());
        } finally { lock.unlock(); }
    }

