    /** Rewrites one PBRole from the persisted fitting-room state. Returns true if anything moved. */
    boolean applyAvatarState(android.content.SharedPreferences st, org.json.JSONObject role) throws Exception {
        long rid = role.optLong("id", 0);
        if (rid == 0) return false;
        boolean changed = false;
        org.json.JSONArray modes = role.optJSONArray("avatarTemplate");
        for (int i = 0; modes != null && i < modes.length(); i++) {
            org.json.JSONObject m = modes.getJSONObject(i);
            int mid = m.optInt("id", i + 1);
            String csv = st.getString("av_mode_" + rid + "_" + mid, null);
            if (csv != null) { m.put("avatars", idArray(csv)); changed = true; }
            String nm = st.getString("av_name_" + rid + "_" + mid, null);
            if (nm != null && !nm.equals(m.optString("name", ""))) { m.put("name", nm); changed = true; }
        }
        int cur = st.getInt("av_cur_" + rid, 0);
        if (cur > 0 && cur != role.optInt("currentAvatar", 1)) { role.put("currentAvatar", cur); changed = true; }

        // PBRole.clothes is a mirror, not a fourth opinion: InfoRole:UpdateAvatarMode rebuilds it
        // from whichever mode is current, and the club-room model reads clothes. Only count it as a
        // change when the mirror is actually wrong -- a clean boot has no persisted state at all, and
        // an unconditional flag here made the overlay log fire on every login, which is not evidence.
        int active = cur > 0 ? cur : role.optInt("currentAvatar", 1);
        for (int i = 0; modes != null && i < modes.length(); i++) {
            if (modes.getJSONObject(i).optInt("id", i + 1) != active) continue;
            org.json.JSONArray worn = modes.getJSONObject(i).optJSONArray("avatars");
            org.json.JSONArray now = role.optJSONArray("clothes");
            if (worn != null && (now == null || !now.toString().equals(worn.toString()))) {
                role.put("clothes", new org.json.JSONArray(worn.toString()));
                changed = true;
            }
            break;
        }

        org.json.JSONArray owned = role.optJSONArray("avatars");
        if (owned == null) { owned = new org.json.JSONArray(); role.put("avatars", owned); }
        String csv = st.getString("av_owned_" + rid, "");
        if (!csv.isEmpty() && grantInto(owned, idArray(csv)) > 0) changed = true;
        java.util.Map<String, ?> all = st.getAll();
        for (java.util.Map.Entry<String, ?> e : all.entrySet()) {
            if (!e.getKey().startsWith("av_bind_")) continue;
            if (((Number) e.getValue()).intValue() != (int) rid) continue;
            long avatarId = Long.parseLong(e.getKey().substring("av_bind_".length()));
            if (grantInto(owned, new org.json.JSONArray().put(avatarId)) > 0) changed = true;
        }
        return changed;
    }

