    byte[] liveKey() {
        if (liveSessionKey == null) {
            liveSessionKey = new byte[32];
            new java.security.SecureRandom().nextBytes(liveSessionKey);
        }
        return liveSessionKey;
    }

    byte[] verifyKey(int protocol, byte[] body, long playerId, String platform, String signature) throws Exception {
        final byte[] session = liveKey();
        byte[][] keys = {bootstrapKey, authKey, session};
        String[] names = {"bootstrap", "auth", "session"};
        if (sessionPad != null) {
            keys = new byte[][]{bootstrapKey, authKey, session, sessionPad,
                    xor(sessionPad, sessionXor), xor(sessionPad, session),
                    xor(sessionPad, session, sessionXor), xor(session, sessionXor),
                    xor(authKey, sessionXor)};
            names = new String[]{"bootstrap", "auth", "session", "pad", "pad^xor", "pad^session",
                    "sent-session", "session^xor", "auth^xor"};
        }
        for (int i = 0; i < keys.length; i++) {
            String expect = requestSignature(keys[i], protocol, body, playerId, platform);
            if (MessageDigest.isEqual(expect.getBytes(StandardCharsets.UTF_8), signature.toLowerCase().getBytes(StandardCharsets.UTF_8))) {
                L.log(null, "verified P" + protocol + " key=" + names[i]);
                return keys[i];
            }
        }
        // Answering anyway is the cheap discriminator: if the client walks away from the title on an
        // unsigned-by-its-own-key response, request verification was never the gate; if it retries,
        // the response signature really is checked and only the key is unknown.
        L.log(null, "assume P" + protocol + " key=session for the response");
        return session;
    }

